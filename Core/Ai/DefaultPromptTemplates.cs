    /// <summary>
    /// Gemini へ字幕（SRT）を作らせる依頼文（v1.12。VideoCaptionLight の既定プロンプトを元に、字幕の見た目・位置・サイズの提案を除き、
    /// ManualVideoStudio の字幕の規則（<see cref="Editing.SubtitleValidator"/>）に合わせた）。
    /// 時刻は添付する字幕依頼用動画（カット後の本編＝完成動画の本編部分と同じ時間軸。タイトルは含まない）の先頭からの時刻。動画の説明は利用者が Gemini で書き換える。
    /// 規則の数値（行数・文字数・最短表示時間）を変えたら、ここも合わせる（SubtitleValidator と二重管理）。
    /// </summary>
    public const string SubtitleRequest = """
        添付したMP4動画を最初から最後まで詳細に解析し、操作説明用の字幕（キャプション）をSRT形式で作成してください。

        この動画は、PC画面をキャプチャした操作説明動画です。
        GUI操作、CLI操作、SSH操作、コンソール操作、またはそれらが混在する可能性があります。


        【今回の動画の内容】

        <ここに動画の内容を書く>

        例：
        ・FortiGate 60Fの初期セットアップ

        ============================================================
        【動画について】
        ============================================================

        ・PC画面をキャプチャした操作説明動画です。（解像度 {{VIDEO_RESOLUTION}}、長さ {{EDITED_DURATION}}）

        ・ブラウザ、アプリケーション、デスクトップ全体、コンソール、SSHターミナル等が撮影されている可能性があります。

        ・不要な部分はカット済みの動画です。添付した動画の先頭を 00:00:00,000 として時刻を付けてください。

        ・映像そのものを必ず確認し、画面上で実際に行われている操作を基準に判断してください。

        ・音声が存在する場合は、操作内容を理解するための補助情報として使用してください。
          音声をそのまま文字起こししないでください（「えー」「あのー」などのフィラー、言い直し、雑談は字幕へ入れないでください）。
          映像と音声の内容が矛盾する場合は、画面上で確認できる操作を優先してください。
          音声だけで説明され、画面から確認できない内容は、事実として断定しないでください。


        ============================================================
        【動画解析】
        ============================================================

        動画のタイムラインを最初から最後まで確認し、特に以下を重点的に解析してください。

        ・画面遷移、メニュー選択、設定画面を開いた操作

        ・設定値の入力または変更、チェックボックスや選択肢の変更

        ・Apply、OK、Save、Next、Submit等による設定反映

        ・ログイン、ログアウト、再ログイン

        ・警告画面、エラー画面、処理完了画面、設定結果の確認

        ・CLIで入力したコマンドと、実行したタイミング、実行後の結果確認

        ・SSH接続、切断、再接続、設定ファイルの編集

        ・サービスの起動、停止、再起動、状態確認

        短時間だけ表示される画面、メニュー、ダイアログ等も可能な範囲で確認してください。


        ============================================================
        【推測について】
        ============================================================

        画面から確認できない内容を推測しないでください。

        判断できない操作については、無理に字幕を作成しないでください。

        製品仕様や一般的な操作方法から推測して、実際には動画で行っていない操作を追加しないでください。


        ============================================================
        【想定視聴者】
        ============================================================

        初心者でも動画を見ながら操作の流れを理解できるようにしてください。

        長い講義説明は不要です。動画を見ながら操作内容を把握するための補助字幕として作成してください。


        ============================================================
        【字幕の基本方針】
        ============================================================

        字幕は短く、原則として1～2行にしてください。何を操作しているのか分かる文章にしてください。

        良い例：

        「［System］→［Settings］を開きます。」

        「Time zoneを「Asia/Tokyo」に変更します。」

        「［Apply］をクリックして設定を反映します。」

        避ける例：

        「ここをクリックします。」

        「次に進みます。」

        「設定します。」

        対象が分からない文章は避けてください。

        GUI画面では、製品名、メニュー名、設定項目名、ボタン名を画面に表示されている名称のまま使用し、
        クリックそのものではなく操作内容を説明してください。


        ============================================================
        【CLI・SSH・コンソール操作の場合】
        ============================================================

        1. コマンドを入力している途中ではなく、原則としてEnter等で実行したタイミングを基準にしてください。

        2. 画面に表示されたコマンド全文を単純に字幕へコピーせず、「何のためにそのコマンドを実行しているのか」が分かる字幕にしてください。

        例：
        画面：ip addr show → 字幕：「IPアドレスの設定状況を確認します。」
        画面：systemctl restart named → 字幕：「DNSサービスを再起動して設定を反映します。」

        3. 短いコマンドで、コマンド名そのものが重要な場合は、コマンド名を含めても構いません。
        例：「`ip addr`を実行してIPアドレスを確認します。」

        4. 大量のコマンド出力を逐一字幕化しないでください。長いログ出力、スクロール、待ち時間には、必要がない限り字幕を付けないでください。

        5. シェルプロンプト、ホスト名、ユーザー名、カレントディレクトリ等をコマンドと誤認しないでください。

        6. vi、vim、nano等で設定ファイルを編集している場合、キー操作を細かく字幕化せず、
           「DNS設定ファイルを編集します。」「設定を保存してエディタを終了します。」程度にまとめてください。

        必要な場合のみ、操作目的を短く補足してください。ただし長い講義説明にはしないでください。


        ============================================================
        【字幕を付ける頻度・表示時間】
        ============================================================

        常に字幕を表示する必要はありません。操作内容または画面の意味が変わるポイントを中心に作成してください。

        同じ操作が続いている場合は、字幕を不必要に細分化しないでください。
        単なる待ち時間、マウス移動だけの時間、長いログ表示、スクロールだけの操作は、字幕なしで構いません。

        字幕を読んでいる間に次の操作へ進んでしまわないよう、文字量に見合った表示時間を確保してください。
        操作より大幅に先行して表示しないでください。原則として、その操作を開始する直前から操作中に表示してください。


        ============================================================
        【認証情報・機密情報】
        ============================================================

        パスワード、秘密鍵、APIキー、アクセストークン、セッショントークン、認証情報、個人情報などが画面に表示されても、
        その値を字幕には記載しないでください。必要に応じて「パスワードを入力します。」のような一般的な表現にしてください。

        IPアドレス、ホスト名、ドメイン名等も、操作説明上必要がない場合は不用意に字幕へ転記しないでください。


        ============================================================
        【SRTの条件（必ず守ってください）】
        ============================================================

        ・文字コードはUTF-8、連番は1から順に付ける

        ・時刻は HH:MM:SS,mmm --> HH:MM:SS,mmm の形式（時・分・秒は2桁、ミリ秒は3桁、秒とミリ秒の区切りはカンマ）

        ・時刻は添付した動画の先頭（00:00:00,000）からの時刻にする

        ・字幕ブロックの間には空行を1行入れる

        ・1件の字幕は最大2行（どうしても必要な場合でも3行以内）、改行を除いて200文字以内にする。目安は1行あたり全角25文字程度

        ・表示時間は最短でも0.2秒以上。読める長さ（目安として2秒以上）を確保する

        ・字幕同士の表示時間を重ねない（前の字幕の終了時刻 ≦ 次の字幕の開始時刻）。同時に2つの字幕を表示しない

        ・最後の字幕の終了時刻は、動画の長さ（{{EDITED_DURATION}}）を超えないようにする

        ・無理に動画全編へ字幕を付けない（操作説明が不要な時間帯は字幕なしでよい）

        ・字幕の位置・文字の大きさ・フォント・背景などの見た目は、このあとアプリ側で設定するため、提案しないでください


        ============================================================
        【最終出力】
        ============================================================

        以下の順番で出力してください。

        1. 動画の解析結果（簡潔に）

        2. 字幕一覧表（| 開始時刻 | 終了時刻 | 字幕 | 画面上で確認した操作 | の表）

        3. 完成版SRT

        一覧表を作成した後、次の点を再確認し、問題があれば修正してから完成版SRTを出力してください。

        ・操作内容と時刻に矛盾がないか

        ・字幕が操作より大幅に先行していないか

        ・字幕同士の時間が重なっていないか、最後の字幕が動画の長さを超えていないか

        ・表示時間が短すぎないか、文章が長すぎないか

        ・画面から確認できない内容を推測していないか

        ・音声をそのまま文字起こししていないか

        完成版SRTは、コピーしてそのままSRTデータとして使用できるように、1つのコードブロック内に出力してください。
        コードブロックは以下の形式にしてください。

        ```srt
        1
        00:00:01,000 --> 00:00:05,000
        字幕
        ```
        """;

    public const string CutAnalysis = """
        あなたは Windows 操作マニュアル動画の編集アシスタントです。
        添付した動画「{{VIDEO_FILENAME}}」（長さ {{VIDEO_DURATION}}）を最初から最後まで確認し、
        視聴者にとって不要な部分（削除してよい区間）の候補を挙げてください。
        長い待ち時間などは、結果を確認するのに必要な最初の数秒を残し、それ以降の区間だけを候補にしてください。
        最終的に削除するかどうかは人間が判断します。迷う箇所は confidence を低くして候補に含めてください。

        ## 候補にするもの
        - 操作をせずに待っている時間
        - 読み込み・処理の待ち時間（長すぎる部分）
        - 操作ミスをして戻った・やり直した部分
        - 意味のないマウス移動・迷っている動き
        - 同じ画面を必要以上に長く表示している部分
        - 本筋の手順と関係のない操作

        ## できるだけ残すもの（候補にしない。待ち時間は必要な最初の数秒を残して、それ以降だけを候補にする）
        - 操作した結果を確認するのに必要な時間
        - 字幕・キャプションを読むのに必要な時間
        - 手順の理解に必要な画面
        - 処理が完了したことが分かるまでの必要な待ち時間

        ## すでに確定している編集（参考。これと重なる候補は不要）
        {{CUT_SEGMENTS}}

        ## 出力形式
        - start / end は動画の先頭からの時刻を "HH:MM:SS.mmm" 形式で書く
        - action は常に "remove"（その区間を削除する）
        - confidence は 0.0～1.0（削除してよい確からしさ）
        - reason は{{LANGUAGE}}で、なぜ不要と判断したかを簡潔に書く
        - 次の形式の JSON のみを返すこと

        {
          "cuts": [
            {
              "start": "00:01:20.200",
              "end": "00:01:27.800",
              "action": "remove",
              "confidence": 0.91,
              "reason": "操作完了後に長い待機時間がある"
            }
          ]
        }
        """;

